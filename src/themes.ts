/**
 * Apply a theme by setting CSS custom properties on the document root.
 */
export function applyTheme(themeId: string): void {
  const theme = THEMES.find((t) => t.id === themeId);
  if (!theme) return;

  const root = document.documentElement;
  Object.entries(theme.vars).forEach(([prop, value]) => {
    root.style.setProperty(prop, value);
  });

  // Handle light themes — toggle a class for orb/canvas visibility tweaks
  const isLight = ["light", "pastel", "minimal-neutral"].includes(themeId);
  document.body.classList.toggle("theme-light", isLight);
  document.body.classList.toggle("theme-dark", !isLight);

  // Persist choice
  localStorage.setItem("portfolio-theme", themeId);

  // Update active state in UI
  document.querySelectorAll<HTMLElement>(".theme-option").forEach((opt) => {
    opt.classList.toggle("active", opt.dataset.theme === themeId);
  });
}

/**
 * Load saved theme or apply default.
 */
export function loadSavedTheme(): void {
  const saved = localStorage.getItem("portfolio-theme");
  applyTheme(saved || "dark");
}
